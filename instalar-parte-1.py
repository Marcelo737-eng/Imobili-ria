def carregar_parte(numero):
    """Le a variavel DADOS de outro arquivo instalar-parte-N.py."""
    arquivo = PASTA / ("instalar-parte-%d.py" % numero)
    if not arquivo.exists():
        return None
    spec = importlib.util.spec_from_file_location("parte_%d" % numero, arquivo)
    modulo = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(modulo)
    return getattr(modulo, "DADOS", None)


def juntar():
    pedacos = [DADOS]
    faltando = []
    for n in range(2, TOTAL_PARTES + 1):
        try:
            d = carregar_parte(n)
        except Exception:
            d = None
        if d is None:
            faltando.append(n)
        else:
            pedacos.append(d)

    if faltando:
        print("=" * 70)
        print("  FALTAM ARQUIVOS PARA CONCLUIR A INSTALACAO")
        print("=" * 70)
        for n in faltando:
            print("  Nao encontrei: instalar-parte-%d.py" % n)
        print("")
        print("  Baixe as %d partes e coloque TODAS nesta pasta:" % TOTAL_PARTES)
        print("     " + str(PASTA))
        print("")
        print("  Depois execute novamente este arquivo.")
        print("=" * 70)
        encerrar()

    return "".join("".join(p.split()) for p in pedacos)


def extrair(b64):
    try:
        bruto = lzma.decompress(base64.b64decode(b64))
    except Exception as exc:
        print("=" * 70)
        print("  OS ARQUIVOS BAIXADOS PARECEM INCOMPLETOS")
        print("=" * 70)
        print("  Detalhe tecnico: %s" % exc)
        print("")
        print("  Provavelmente um dos arquivos foi baixado pela metade.")
        print("  Baixe as %d partes novamente e tente outra vez." % TOTAL_PARTES)
        print("=" * 70)
        encerrar()

    pos = 0
    total = 0
    while pos < len(bruto):
        fim = bruto.index(b"\n", pos)
        nome = bruto[pos:fim].decode("utf-8")
        pos = fim + 1
        fim = bruto.index(b"\n", pos)
        tam = int(bruto[pos:fim])
        pos = fim + 1
        alvo = DESTINO / nome
        alvo.parent.mkdir(parents=True, exist_ok=True)
        alvo.write_bytes(bruto[pos:pos + tam])
        pos += tam
        total += 1
    return total


